import test from 'node:test';
import assert from 'node:assert/strict';
import { Wallet, AbiCoder, keccak256, getBytes, parseEther } from 'ethers';
import { compile } from '../scripts/compile-contracts.js';
import { evm } from './evm-helper.js';

test('ERC-20 grants, funded escrow, exact worker payout, replay protection and expiry refunds', { timeout: 60000 }, async () => {
  const chain = await evm(), [coordinator, payer, worker, stranger] = chain.accounts, issuer = Wallet.createRandom();
  const compiled = compile(), token = await chain.deploy(compiled.LLMeshToken, [issuer.address]);
  const escrow = await chain.deploy(compiled.LLMeshEscrow, [token.address, coordinator.address]);
  const nostr = '0x' + 'a'.repeat(64), deadline = Math.floor(Date.now() / 1000) + 600;
  const digest = keccak256(AbiCoder.defaultAbiCoder().encode(['uint256','address','address','bytes32','uint256'], [chain.chainId, token.address, payer.address, nostr, deadline]));
  const signature = await issuer.signMessage(getBytes(digest));
  await token.send(payer, 'register', [payer.address, nostr, deadline, signature]);
  assert.equal((await token.read('balanceOf', [payer.address]))[0], parseEther('100'));
  await assert.rejects(token.send(payer, 'register', [payer.address, nostr, deadline, signature]));
  await assert.rejects(token.send(stranger, 'register', [payer.address, nostr, deadline, signature]));
  const clientId = '0x' + '1'.repeat(64), id = (await escrow.read('jobId', [payer.address, clientId]))[0];
  await assert.rejects(escrow.send(stranger, 'lock', [clientId, nostr, worker.address, 0]));
  await token.send(payer, 'approve', [escrow.address, parseEther('2')]);
  await escrow.send(payer, 'lock', [clientId, nostr, worker.address, 0]);
  assert.equal((await token.read('balanceOf', [payer.address]))[0], parseEther('99'));
  await assert.rejects(escrow.send(stranger, 'settle', [id]));
  await escrow.send(coordinator, 'settle', [id]);
  assert.equal((await token.read('balanceOf', [worker.address]))[0], parseEther('1'));
  await assert.rejects(escrow.send(coordinator, 'settle', [id]));
  await assert.rejects(escrow.send(payer, 'lock', [clientId, nostr, worker.address, 0]));
  const secondClient = '0x' + '2'.repeat(64), second = (await escrow.read('jobId', [payer.address, secondClient]))[0]; await escrow.send(payer, 'lock', [secondClient, nostr, worker.address, 0]);
  await assert.rejects(escrow.send(payer, 'refund', [second]));
  chain.advance(90001); await escrow.send(payer, 'refund', [second]);
  assert.equal((await token.read('balanceOf', [payer.address]))[0], parseEther('99'));
  const thirdClient = '0x' + '3'.repeat(64), third = (await escrow.read('jobId', [payer.address, thirdClient]))[0];
  await token.send(payer, 'approve', [escrow.address, parseEther('3')]);
  await escrow.send(payer, 'lock', [thirdClient, nostr, worker.address, 2]);
  assert.equal((await escrow.read('jobs', [third])).amount, parseEther('3'));
  await escrow.send(coordinator, 'settle', [third]);
  assert.equal((await token.read('balanceOf', [worker.address]))[0], parseEther('4'));
  await assert.rejects(escrow.send(payer, 'lock', ['0x' + '4'.repeat(64), nostr, worker.address, 3]));
});
