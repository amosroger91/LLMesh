import test from 'node:test';
import assert from 'node:assert/strict';
import { Wallet, AbiCoder, keccak256, getBytes, parseEther } from 'ethers';
import { compile } from '../scripts/compile-contracts.js';
import { evm } from './evm-helper.js';

test('metered ERC-20 escrow pays actual usage, returns unused reservation, bounds usage and grants once', {timeout:60000},async()=>{
 const chain=await evm(),[coordinator,payer,worker,stranger]=chain.accounts,issuer=Wallet.createRandom();
 const compiled=compile(),token=await chain.deploy(compiled.LLMeshToken,[issuer.address]);
 const escrow=await chain.deploy(compiled.LLMeshEscrow,[token.address,coordinator.address]);
 const nostr='0x'+'a'.repeat(64),deadline=Math.floor(Date.now()/1000)+600;
 const signature=await issuer.signMessage(getBytes(keccak256(AbiCoder.defaultAbiCoder().encode(['uint256','address','address','bytes32','uint256'],[chain.chainId,token.address,payer.address,nostr,deadline]))));
 await token.send(payer,'register',[payer.address,nostr,deadline,signature]);
 assert.equal((await token.read('balanceOf',[payer.address]))[0],parseEther('100000'));
 await assert.rejects(token.send(payer,'register',[payer.address,nostr,deadline,signature]));
 const client='0x'+'1'.repeat(64),id=(await escrow.read('jobId',[payer.address,client]))[0];
 await token.send(payer,'approve',[escrow.address,parseEther('10000')]);
 for(const budget of [0,34817])await assert.rejects(escrow.send(payer,'lock',[client,nostr,worker.address,budget]));
 await assert.rejects(escrow.send(stranger,'lock',[client,nostr,worker.address,1000]));
 await escrow.send(payer,'lock',[client,nostr,worker.address,1000]);
 assert.equal((await token.read('balanceOf',[payer.address]))[0],parseEther('99000'));
 await assert.rejects(escrow.send(stranger,'settle',[id,137]));
 await assert.rejects(escrow.send(coordinator,'settle',[id,1001]));
 await escrow.send(coordinator,'settle',[id,137]);
 assert.equal((await token.read('balanceOf',[worker.address]))[0],parseEther('137'));
 assert.equal((await token.read('balanceOf',[payer.address]))[0],parseEther('99863'));
 assert.equal((await escrow.read('jobs',[id])).usedCredits,137n);
 assert.equal((await token.read('balanceOf',[escrow.address]))[0],0n);
 await assert.rejects(escrow.send(coordinator,'settle',[id,137]));
 await assert.rejects(escrow.send(payer,'lock',[client,nostr,worker.address,1000]));
 const secondClient='0x'+'2'.repeat(64),second=(await escrow.read('jobId',[payer.address,secondClient]))[0];
 await escrow.send(payer,'lock',[secondClient,nostr,worker.address,1000]);await assert.rejects(escrow.send(payer,'refund',[second]));
 chain.advance(90001);await escrow.send(payer,'refund',[second]);
 assert.equal((await token.read('balanceOf',[payer.address]))[0],parseEther('99863'));
 const zeroClient='0x'+'3'.repeat(64),zero=(await escrow.read('jobId',[payer.address,zeroClient]))[0];
 await escrow.send(payer,'lock',[zeroClient,nostr,worker.address,500]);await escrow.send(coordinator,'settle',[zero,0]);
 assert.equal((await token.read('balanceOf',[payer.address]))[0],parseEther('99863'));
});
