import test from 'node:test';
import assert from 'node:assert/strict';
import { AbiCoder, keccak256, getBytes, parseEther } from 'ethers';
import { compile } from '../scripts/compile-contracts.js';
import { evm } from './evm-helper.js';
test('relayed grants, namespaced lock IDs, worker delivery claims and signed failure refunds', async () => {
  const chain = await evm(), [coordinator, payer, worker, stranger] = chain.accounts;
  const compiled = compile(), token = await chain.deploy(compiled.LLMeshToken, [coordinator.address]);
  const escrow = await chain.deploy(compiled.LLMeshEscrow, [token.address, coordinator.address]);
  const abi = AbiCoder.defaultAbiCoder(), nostr = '0x' + 'a'.repeat(64), clientId = '0x' + '1'.repeat(64);
  const deadline = Math.floor(Date.now() / 1000) + 600;
  const signature = await coordinator.signMessage(getBytes(keccak256(abi.encode(['uint256','address','address','bytes32','uint256'], [chain.chainId, token.address, payer.address, nostr, deadline]))));
  await token.send(stranger, 'register', [payer.address, nostr, deadline, signature]);
  assert.equal((await token.read('balanceOf', [payer.address]))[0], parseEther('100'));
  await token.send(payer, 'approve', [escrow.address, parseEther('2')]);
  const id = (await escrow.read('jobId', [payer.address, clientId]))[0];
  assert.notEqual(id, (await escrow.read('jobId', [stranger.address, clientId]))[0]);
  await escrow.send(payer, 'lock', [clientId, nostr, worker.address, 0]);
  await assert.rejects(escrow.send(coordinator, 'refund', [id]));
  const outputHash = '0x' + '2'.repeat(64);
  const delivered = await coordinator.signMessage(getBytes(keccak256(abi.encode(['uint256','address','bytes32','bytes32'], [chain.chainId, escrow.address, id, outputHash]))));
  chain.advance(3601);
  await assert.rejects(escrow.send(payer, 'refund', [id]));
  await escrow.send(worker, 'claimDelivered', [id, outputHash, delivered]);
  assert.equal((await token.read('balanceOf', [worker.address]))[0], parseEther('1'));
  const secondClient = '0x' + '3'.repeat(64), second = (await escrow.read('jobId', [payer.address, secondClient]))[0];
  await escrow.send(payer, 'lock', [secondClient, nostr, worker.address, 0]);
  const refundDigest = keccak256(abi.encode(['uint256','address','bytes32','string'], [chain.chainId, escrow.address, second, 'refund-failed']));
  const failed = await worker.signMessage(getBytes(refundDigest));
  await escrow.send(coordinator, 'refundFailed', [second, failed]);
  assert.equal((await token.read('balanceOf', [payer.address]))[0], parseEther('99'));
  await assert.rejects(escrow.send(worker, 'claimDelivered', [second, outputHash, delivered]));
});
